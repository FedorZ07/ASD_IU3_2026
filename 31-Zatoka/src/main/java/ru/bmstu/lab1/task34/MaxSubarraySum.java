package ru.bmstu.lab1.task34;

/**
 * Задача 34. Максимальная сумма подмассива.
 * Вход: массив из n целых чисел (могут быть отрицательные).
 * Выход: максимальная сумма непрерывного подмассива.
 * Требование: O(n) (алгоритм Кадане).
 *
 * <p>Идея алгоритма Кадане: идём слева направо и для каждой позиции i храним
 * лучшую сумму подмассива, который заканчивается ровно в i. Такой подмассив
 * либо продолжает лучший подмассив, закончившийся в i - 1, либо начинается
 * заново с arr[i] - выбираем, что больше. Ответ - максимум по всем i.
 */
public class MaxSubarraySum {

    private MaxSubarraySum() {
    }

    /**
     * Находит максимальную сумму непустого непрерывного подмассива.
     * Если все числа отрицательные, ответом будет наибольшее из них
     * (подмассив из одного элемента), а не 0.
     *
     * @param arr непустой массив чисел
     * @return максимальная сумма подмассива
     * @throws IllegalArgumentException если массив пустой
     */
    public static long find(int[] arr) {
        if (arr.length == 0) {
            throw new IllegalArgumentException("Массив не должен быть пустым");
        }
        long current = arr[0];
        long best = arr[0];
        for (int i = 1; i < arr.length; i++) {
            // если накопленная сумма отрицательная, выгоднее начать заново с arr[i]
            current = Math.max(current + arr[i], arr[i]);
            best = Math.max(best, current);
        }
        return best;
    }
}
