package ru.bmstu.lab1.task14;

/**
 * Задача 14. Сортировка вставками.
 * Вход: массив из n целых чисел.
 * Выход: массив, отсортированный по невозрастанию.
 * Требование: реализовать сортировку вставками вручную.
 */
public class InsertionSort {

    private InsertionSort() {
    }

    /**
     * Сортирует массив по невозрастанию сортировкой вставками (на месте).
     * Левая часть arr[0..i-1] всегда уже отсортирована. Берём arr[i]
     * и сдвигаем вправо все элементы слева, которые меньше него,
     * а потом ставим arr[i] на освободившееся место.
     *
     * @param arr массив, который нужно отсортировать
     */
    public static void sort(int[] arr) {
        for (int i = 1; i < arr.length; i++) {
            int current = arr[i];
            int j = i - 1;
            // строгое сравнение: равные элементы не двигаем, сортировка устойчивая
            while (j >= 0 && arr[j] < current) {
                arr[j + 1] = arr[j];
                j--;
            }
            arr[j + 1] = current;
        }
    }
}
