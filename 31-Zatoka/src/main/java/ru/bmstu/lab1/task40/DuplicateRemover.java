package ru.bmstu.lab1.task40;

/**
 * Задача 40. Удаление дубликатов.
 * Вход: отсортированный по неубыванию массив из n целых чисел.
 * Выход: массив без дубликатов, сохраняя порядок.
 * Требование: O(n), модификация исходного массива на месте.
 *
 * <p>Идея: так как массив отсортирован, одинаковые числа стоят рядом.
 * Указатель write показывает, куда положить следующее новое число.
 * Идём по массиву и, встретив число, отличное от последнего записанного,
 * ставим его на позицию write.
 */
public class DuplicateRemover {

    private DuplicateRemover() {
    }

    /**
     * Удаляет повторы из отсортированного массива на месте.
     * После вызова первые k элементов массива - это все разные числа
     * в исходном порядке; остальные элементы больше не важны.
     *
     * @param arr массив, отсортированный по неубыванию
     * @return k - количество разных чисел (новая длина массива)
     */
    public static int removeDuplicates(int[] arr) {
        if (arr.length == 0) {
            return 0;
        }
        int write = 1;
        for (int read = 1; read < arr.length; read++) {
            if (arr[read] != arr[write - 1]) {
                arr[write] = arr[read];
                write++;
            }
        }
        return write;
    }
}
